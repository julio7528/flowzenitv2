create table public.recorrente (
  id bigint generated by default as identity primary key,
  demanda text not null check (char_length(btrim(demanda)) > 0),
  hora time without time zone not null,
  dia_semana smallint not null check (dia_semana between 1 and 7),
  data_inicial date not null,
  data_final date not null,
  constraint recorrente_periodo_check check (data_inicial <= data_final)
);

create index recorrente_dia_periodo_idx
  on public.recorrente (dia_semana, data_inicial, data_final);

alter table public.recorrente enable row level security;

grant select, insert, update, delete on table public.recorrente to anon;
grant usage, select on sequence public.recorrente_id_seq to anon;

create policy public_can_read_recorrente
on public.recorrente
for select to anon
using (true);

create policy public_can_create_recorrente
on public.recorrente
for insert to anon
with check (true);

create policy public_can_update_recorrente
on public.recorrente
for update to anon
using (true)
with check (true);

create policy public_can_delete_recorrente
on public.recorrente
for delete to anon
using (true);
