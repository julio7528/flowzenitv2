create table public.demandas (
  id bigint generated by default as identity primary key,
  demanda text not null check (char_length(btrim(demanda)) > 0),
  tipo smallint not null check (tipo in (1, 2, 3)),
  raizid bigint references public.demandas(id) on delete cascade,
  constraint demandas_raizid_by_type check (
    (tipo = 1 and raizid is null)
    or (tipo in (2, 3) and raizid is not null)
  )
);

create index demandas_raizid_idx on public.demandas (raizid);

create or replace function public.validar_hierarquia_demandas()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  tipo_pai smallint;
begin
  if new.tipo = 1 then
    if new.raizid is not null then
      raise exception 'Uma demanda principal não pode ter raizid.'
        using errcode = '23514';
    end if;
    return new;
  end if;

  select parent.tipo
    into tipo_pai
    from public.demandas as parent
    where parent.id = new.raizid;

  if not found then
    raise exception 'O registro pai informado não existe.'
      using errcode = '23503';
  end if;

  if new.tipo = 2 and tipo_pai <> 1 then
    raise exception 'Uma tarefa deve pertencer a uma demanda.'
      using errcode = '23514';
  end if;

  if new.tipo = 3 and tipo_pai <> 2 then
    raise exception 'Uma subtarefa deve pertencer a uma tarefa.'
      using errcode = '23514';
  end if;

  return new;
end;
$$;

create trigger demandas_validar_hierarquia
before insert or update of tipo, raizid on public.demandas
for each row execute function public.validar_hierarquia_demandas();

alter table public.demandas enable row level security;

grant select, insert on table public.demandas to anon;
grant usage, select on sequence public.demandas_id_seq to anon;

create policy public_can_read_demandas
on public.demandas
for select to anon
using (true);

create policy public_can_create_demandas
on public.demandas
for insert to anon
with check (true);
